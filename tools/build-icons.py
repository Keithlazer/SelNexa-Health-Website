"""Build the site's icon font: a subset of Font Awesome Free 6.4.0 holding only the icons the pages use.

Writes assets/fonts/icons-{solid,regular,brands}.woff2 and styles/icons.css.

The Font Awesome fonts are licensed under the SIL Open Font License 1.1 with the Reserved Font Name
"Font Awesome", so the subset is a Modified Version and is renamed "SelNexa Icons". The licence is
copied to assets/fonts/LICENSE-icons.txt.

Run again after adding an <i class="fas fa-..."> icon to a page:

    pip install fonttools brotli
    npm pack @fortawesome/fontawesome-free@6.4.0 && tar -xzf fortawesome-fontawesome-free-6.4.0.tgz
    python tools/build-icons.py path/to/package
"""

import re
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
PKG = Path(sys.argv[1]) if len(sys.argv) > 1 else None
if not PKG or not (PKG / "css" / "all.css").exists():
    sys.exit("usage: python tools/build-icons.py <path to unpacked @fortawesome/fontawesome-free 6.4.0 package>")

STYLES = {
    # class names -> (font file, our family name, weight, output name)
    "solid": (("fa", "fas", "fa-solid"), "fa-solid-900.ttf", "SelNexa Icons", 900, "icons-solid"),
    "regular": (("far", "fa-regular"), "fa-regular-400.ttf", "SelNexa Icons", 400, "icons-regular"),
    "brands": (("fab", "fa-brands"), "fa-brands-400.ttf", "SelNexa Brand Icons", 400, "icons-brands"),
}
MODIFIERS = {"fa-solid", "fa-regular", "fa-brands", "fa-fw", "fa-lg", "fa-2x", "fa-3x", "fa-spin"}

# icon name -> codepoint, from the package CSS
codepoints = {}
for selector, code in re.findall(r"\.(fa-[a-z0-9-]+)::?before\s*\{\s*content:\s*\"\\([0-9a-f]+)\"", (PKG / "css" / "all.css").read_text("utf8")):
    codepoints.setdefault(selector, int(code, 16))

# icons used in published pages and scripts, grouped by style
pages = [p for p in ROOT.glob("*.html") if p.name != "modern-design-demo.html"]  # the demo file is not published
pages += [p for d in ("blog", "resources", "solutions") for p in (ROOT / d).glob("*.html")]
pages += list((ROOT / "js").glob("*.js")) + list((ROOT / "includes").glob("*.html"))
used = {style: set() for style in STYLES}
for page in pages:
    text = page.read_text("utf8", errors="ignore")
    for classes in re.findall(r'class="([^"]*)"', text):
        names = classes.split()
        style = next((s for s, spec in STYLES.items() if any(n in spec[0] for n in names)), None)
        if not style:
            continue
        for name in names:
            if name.startswith("fa-") and name not in MODIFIERS:
                used[style].add(name)

missing = [(s, n) for s, names in used.items() for n in names if n not in codepoints]
if missing:
    sys.exit(f"unknown icon names: {missing}")

out_fonts = ROOT / "assets" / "fonts"
out_fonts.mkdir(parents=True, exist_ok=True)
css = [
    "/*",
    " * Icons: a subset of Font Awesome Free 6.4.0 by Fonticons, Inc. (https://fontawesome.com),",
    " * renamed as the SIL Open Font License 1.1 requires. Licence: /assets/fonts/LICENSE-icons.txt",
    " * Generated by tools/build-icons.py; do not edit by hand.",
    " */",
    "",
]
for style, (_classes, font_file, family, weight, out_name) in STYLES.items():
    if not used[style]:
        continue
    font = TTFont(PKG / "webfonts" / font_file)
    options = subset.Options()
    options.flavor = "woff2"
    options.name_IDs = ["*"]
    options.notdef_outline = True
    options.layout_features = []
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes={codepoints[n] for n in used[style]})
    subsetter.subset(font)
    ps_name = family.replace(" ", "") + "-" + style.capitalize()
    for record in font["name"].names:
        if record.nameID in (1, 16):
            record.string = family
        elif record.nameID in (4,):
            record.string = f"{family} {style.capitalize()}"
        elif record.nameID == 6:
            record.string = ps_name
        elif record.nameID == 3:
            record.string = f"{ps_name}; subset of Font Awesome Free 6.4.0"
    font.flavor = "woff2"
    target = out_fonts / f"{out_name}.woff2"
    font.save(target)
    css += [
        "@font-face {",
        f'  font-family: "{family}";',
        "  font-style: normal;",
        f"  font-weight: {weight};",
        "  font-display: block;",
        f'  src: url("/assets/fonts/{out_name}.woff2") format("woff2");',
        "}",
        "",
    ]
    print(f"{target.relative_to(ROOT)}: {len(used[style])} icons, {target.stat().st_size} bytes")

css += [
    ".fa, .fas, .far, .fab, .fa-solid, .fa-regular, .fa-brands {",
    "  display: inline-block;",
    "  font-style: normal;",
    "  font-variant: normal;",
    "  line-height: 1;",
    "  text-rendering: auto;",
    "  -webkit-font-smoothing: antialiased;",
    "  -moz-osx-font-smoothing: grayscale;",
    "}",
    "",
    '.fa, .fas, .fa-solid { font-family: "SelNexa Icons"; font-weight: 900; }',
    '.far, .fa-regular { font-family: "SelNexa Icons"; font-weight: 400; }',
    '.fab, .fa-brands { font-family: "SelNexa Brand Icons"; font-weight: 400; }',
    "",
]
for name in sorted(set().union(*used.values())):
    css.append(f'.{name}::before {{ content: "\\{codepoints[name]:x}"; }}')
(ROOT / "styles" / "icons.css").write_text("\n".join(css) + "\n", "utf8")

license_text = (PKG / "LICENSE.txt").read_text("utf8")
(out_fonts / "LICENSE-icons.txt").write_text(
    "The icon fonts in this folder (icons-*.woff2) are subsets of the Font Awesome Free 6.4.0 fonts,\n"
    "renamed \"SelNexa Icons\" and \"SelNexa Brand Icons\" because \"Font Awesome\" is a Reserved Font Name.\n"
    "Original licence follows.\n\n" + license_text,
    "utf8",
)
print("styles/icons.css written")
