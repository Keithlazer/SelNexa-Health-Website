// Builds assets/icons/sprite.svg from Phosphor Icons 2.1.1 (@phosphor-icons/core, MIT licence), holding only the icons
// the site uses. It scans the pages, partials and scripts for references like
//   <svg><use href="/assets/icons/sprite.svg#hospital"></use></svg>        duotone, for icon tiles on cards
//   <svg><use href="/assets/icons/sprite.svg#arrow-right-line"></use></svg> regular, for inline and UI icons
// and writes one <symbol> per name. Run by `npm run build:site`; `--check` fails if the sprite is out of date.
//
// Duotone symbols: the back layer has no fill of its own, so it takes the CSS `fill` of the <svg> (gold in
// .ds-icon); the outline uses currentColor (navy). Regular symbols use currentColor only.
// Standalone copies of the icons that CSS uses as masks (EXTRA_FILES) are written next to the sprite.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lib = path.join(root, "node_modules", "@phosphor-icons", "core", "assets");
const outDir = path.join(root, "assets", "icons");
const checkOnly = process.argv.includes("--check");
const EXTRA_FILES = ["arrow-right"];

const sources = [];
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (["node_modules", ".git", "audit", "assets", "styles", "design-assets"].includes(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(html|js|mjs)$/.test(e.name) && !p.includes(`${path.sep}tools${path.sep}`)) sources.push(p);
  }
};
walk(root);
const names = new Set();
for (const f of sources) {
  for (const m of fs.readFileSync(f, "utf8").matchAll(/sprite\.svg#([a-z0-9-]+)/g)) names.add(m[1]);
}

const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const symbols = [...names].sort().map((id) => {
  const line = id.endsWith("-line");
  const base = line ? id.slice(0, -5) : id;
  const file = line ? path.join(lib, "regular", `${base}.svg`) : path.join(lib, "duotone", `${base}-duotone.svg`);
  if (!fs.existsSync(file)) throw new Error(`Phosphor has no ${line ? "regular" : "duotone"} icon "${base}" (used as #${id})`);
  let body = inner(fs.readFileSync(file, "utf8"));
  if (line) body = body.replace(/<path /g, '<path fill="currentColor" ');
  else body = body.replace(/<path (?![^>]*opacity)/g, '<path fill="currentColor" ').replace(/opacity="0\.2"/g, 'opacity="0.45"');
  return `<symbol id="${id}" viewBox="0 0 256 256">${body}</symbol>`;
});
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Phosphor Icons 2.1.1 (MIT, see LICENSE). Generated by tools/build-icons.mjs; do not edit. -->\n${symbols.join("\n")}\n</svg>\n`;

const outputs = new Map([[path.join(outDir, "sprite.svg"), sprite]]);
for (const n of EXTRA_FILES) outputs.set(path.join(outDir, `${n}.svg`), fs.readFileSync(path.join(lib, "regular", `${n}.svg`), "utf8"));
outputs.set(path.join(outDir, "LICENSE"), fs.readFileSync(path.join(root, "node_modules", "@phosphor-icons", "core", "LICENSE"), "utf8"));

let stale = 0;
for (const [file, text] of outputs) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (current === text) continue;
  stale += 1;
  if (checkOnly) console.error(`out of date: ${path.relative(root, file)}`);
  else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); }
}
if (checkOnly && stale) process.exit(1);
console.log(`icon sprite: ${names.size} icons${stale ? (checkOnly ? "" : `, ${stale} file(s) written`) : ", up to date"}`);
