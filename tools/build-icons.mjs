// Builds assets/icons/sprite.svg, holding only the icons the site uses. It scans the pages, partials and scripts for
// references like
//   <svg><use href="/assets/icons/sprite.svg#home-iterate-fast"></use></svg>   a SelNexa site icon (content slots)
//   <svg><use href="/assets/icons/sprite.svg#arrow-right-line"></use></svg>    a Phosphor regular icon (controls, other slots)
//   <svg><use href="/assets/icons/sprite.svg#brand-linkedin"></use></svg>      a company's own logo (share buttons)
// and writes one <symbol> per name. Run by `npm run build:site`; `--check` fails if the sprite is out of date.
//
// Sources, all one style (Phosphor Icons 2.1.1, regular weight, MIT licence):
// - design-assets/icons/selnexa/selnexa-icons-sprite.svg: the 74 named site icons in Keith's icon brief (README.md there).
// - @phosphor-icons/core: any other icon, named "<phosphor name>-line".
// - design-assets/icons/brands/<name>.svg: official logos in their brand colours, named "brand-<name>".
// All icons except the brand logos use currentColor. Standalone copies of icons that CSS uses as masks (EXTRA_FILES)
// are written next to the sprite.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lib = path.join(root, "node_modules", "@phosphor-icons", "core", "assets");
const siteSet = path.join(root, "design-assets", "icons", "selnexa");
const brands = path.join(root, "design-assets", "icons", "brands");
const outDir = path.join(root, "assets", "icons");
const checkOnly = process.argv.includes("--check");
const EXTRA_FILES = ["arrow-right"];

const sources = [];
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (["node_modules", ".git", "audit", "assets", "styles", "design-assets"].includes(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(html|js|mjs)$/.test(e.name) && !p.includes(`${path.sep}tools${path.sep}`)) sources.push(p);
  }
};
walk(root);
const names = new Set();
for (const f of sources) {
  for (const m of fs.readFileSync(f, "utf8").matchAll(/sprite\.svg#([a-z0-9-]+)/g)) names.add(m[1]);
}

const siteIcons = new Map();
for (const m of fs.readFileSync(path.join(siteSet, "selnexa-icons-sprite.svg"), "utf8").matchAll(/<symbol id="([a-z0-9-]+)"[^>]*>([\s\S]*?)<\/symbol>/g)) {
  siteIcons.set(m[1], m[2]);
}

const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const tidy = (body) => body.replace(/<title>[\s\S]*?<\/title>/g, "").replace(/<metadata>[\s\S]*?<\/metadata>/g, "").trim();
const symbols = [...names].sort().map((id) => {
  if (id.startsWith("brand-")) {
    const file = path.join(brands, `${id.slice(6)}.svg`);
    if (!fs.existsSync(file)) throw new Error(`No brand logo design-assets/icons/brands/${id.slice(6)}.svg (used as #${id})`);
    return `<symbol id="${id}" viewBox="0 0 24 24">${tidy(inner(fs.readFileSync(file, "utf8")))}</symbol>`;
  }
  if (siteIcons.has(id)) {
    const body = tidy(siteIcons.get(id)).replace(/<path (?![^>]*fill=)/g, '<path fill="currentColor" ');
    return `<symbol id="${id}" viewBox="0 0 256 256">${body}</symbol>`;
  }
  if (!id.endsWith("-line")) throw new Error(`#${id} is not a SelNexa site icon; use a Phosphor icon as #<name>-line`);
  const file = path.join(lib, "regular", `${id.slice(0, -5)}.svg`);
  if (!fs.existsSync(file)) throw new Error(`Phosphor has no regular icon "${id.slice(0, -5)}" (used as #${id})`);
  const body = tidy(inner(fs.readFileSync(file, "utf8"))).replace(/<path /g, '<path fill="currentColor" ');
  return `<symbol id="${id}" viewBox="0 0 256 256">${body}</symbol>`;
});
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Phosphor Icons 2.1.1 (MIT, see LICENSE-phosphor.txt), with the SelNexa site icon names, and company logos for share buttons. Generated by tools/build-icons.mjs; do not edit. -->\n${symbols.join("\n")}\n</svg>\n`;

const outputs = new Map([[path.join(outDir, "sprite.svg"), sprite]]);
for (const n of EXTRA_FILES) outputs.set(path.join(outDir, `${n}.svg`), fs.readFileSync(path.join(lib, "regular", `${n}.svg`), "utf8"));
outputs.set(path.join(outDir, "LICENSE-phosphor.txt"), fs.readFileSync(path.join(siteSet, "LICENSE-phosphor.txt"), "utf8"));

let stale = 0;
for (const [file, text] of outputs) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (current === text) continue;
  stale += 1;
  if (checkOnly) console.error(`out of date: ${path.relative(root, file)}`);
  else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); }
}
const old = path.join(outDir, "LICENSE");
if (fs.existsSync(old)) {
  stale += 1;
  if (checkOnly) console.error("remove: assets/icons/LICENSE (replaced by LICENSE-phosphor.txt)");
  else fs.rmSync(old);
}
if (checkOnly && stale) process.exit(1);
const site = [...names].filter((n) => siteIcons.has(n)).length;
console.log(`icon sprite: ${names.size} icons (${site} SelNexa site icons)${stale ? (checkOnly ? "" : `, ${stale} file(s) written`) : ", up to date"}`);
